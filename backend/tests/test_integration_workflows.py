def test_runtime_network_guard_blocks_internal_targets(api, sample_app):
    """URLs hidden behind variables pass static validation but are blocked by the engine at run time."""
    project = make_project(api, "Guard", sample_app)
    case = api.post(f"/api/projects/{project['id']}/test-cases", json={"title": "Reach loopback via variable", "steps": [
        {"action": "set_variable", "value": "http://127.0.0.2:9/", "options": {"name": "target"}},
        {"action": "navigate", "value": "{{target}}"},
        {"action": "assert_title", "value": "anything"},
    ]}).json()
    assert case["validation_status"] != "invalid"
    api_case = api.post(f"/api/projects/{project['id']}/test-cases", json={"title": "Metadata via variable", "kind": "api", "steps": [
        {"action": "set_variable", "value": "http://169.254.169.254", "options": {"name": "meta"}},
        {"action": "api_request", "options": {"method": "GET", "url": "{{meta}}/latest/meta-data", "expect": {"status": [200]}}},
    ]}).json()
    ex = _wait_execution(api, api.post(f"/api/projects/{project['id']}/executions",
                                       json={"test_case_ids": [case["id"], api_case["id"]], "timeout_ms": 20000}).json())
    assert ex["status"] == "failed" and ex["failed"] == 2
    for r in ex["results"]:
        assert "blocked by network policy" in r["error_message"]
        assert r["failure"]["category"] == "environment_failure"


def test_pages_that_show_login_in_place_get_login_steps(api, sample_app):
    """Single-page apps often show the sign-in form at the same URL instead of redirecting.
    Discovery must still mark such pages as requiring login, so generated tests sign in first."""
    project = make_project(api, "In-place login")
    disc = api.post(f"/api/projects/{project['id']}/discoveries", json={
        "url": sample_app + "/", "authorized": True, "login_url": "/login", "username": "demo@acme.test",
        "password": "Passw0rd!", "max_pages": 12}).json()
    disc = api.get(f"/api/discoveries/{disc['id']}").json()
    billing = next(p for p in disc["pages"] if p["url"].endswith("/billing"))
    assert billing["requires_login"] is True
    assert billing["forms"] and billing["forms"][0]["fields"][0]["label"] == "Pays *"

    job = api.get(f"/api/generation-jobs/{api.post(f'/api/discoveries/{disc['id']}/generate', json={}).json()['id']}").json()
    cases = [c for c in api.get(f"/api/projects/{project['id']}/test-cases").json()
             if c["id"] in job["result"]["test_case_ids"] and "Renew subscription" in c["title"]]
    assert cases, "expected generated tests for the billing form"
    for c in cases:
        steps = api.get(f"/api/projects/{project['id']}/test-cases/{c['id']}").json()["steps"]
        assert steps[0]["value"] == "/login" and any(s["value"] == "{{password}}" for s in steps)
    ex = _wait_execution(api, api.post(f"/api/projects/{project['id']}/executions",
                                       json={"test_case_ids": [c["id"] for c in cases]}).json())
    assert ex["status"] == "passed", [(r["test_title"], r["error_message"]) for r in ex["results"] if r["status"] != "passed"]


def test_login_steps_use_the_real_sign_in_form(api, sample_app):
    """The sign-in page redirects away once signed in, and a change-password form (several password
    fields) is found first. Login steps must still come from the real sign-in form, and the
    change-password form must never be submitted with valid data."""
    project = make_project(api, "Real login form")
    disc = api.post(f"/api/projects/{project['id']}/discoveries", json={
        "url": sample_app + "/", "authorized": True, "login_url": "/login", "username": "demo@acme.test",
        "password": "Passw0rd!", "max_pages": 15}).json()
    disc = api.get(f"/api/discoveries/{disc['id']}").json()
    assert disc["login_result"]["success"] is True
    assert any(p["url"].endswith("/account/password") for p in disc["pages"])
    job = api.get(f"/api/generation-jobs/{api.post(f'/api/discoveries/{disc['id']}/generate', json={}).json()['id']}").json()
    cases = [c for c in api.get(f"/api/projects/{project['id']}/test-cases").json() if c["id"] in job["result"]["test_case_ids"]]
    by_title = {c["title"]: c for c in cases}

    login = api.get(f"/api/projects/{project['id']}/test-cases/{by_title['Verify login with valid credentials']['id']}").json()["steps"]
    assert login[0]["value"] == "/login"
    assert [s["value"] for s in login if s["action"] == "fill"] == ["{{username}}", "{{password}}"]
    assert not any("New password" in str(s["target"]) for s in login)
    assert not any(t.startswith("Validate form submission: Change password") for t in by_title)

    ex = _wait_execution(api, api.post(f"/api/projects/{project['id']}/executions",
                                       json={"test_case_ids": [c["id"] for c in cases], "workers": 2}).json())
    assert ex["status"] == "passed", [(r["test_title"], r["error_message"][:200]) for r in ex["results"] if r["status"] != "passed"]
