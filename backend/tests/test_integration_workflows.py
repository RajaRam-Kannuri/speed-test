"""End-to-end API workflows against the Acme CRM sample app with real Playwright executions.

Celery runs in eager mode, so discovery, generation and execution jobs execute
in-process using the same code paths as the worker.
"""

import io
import json
import zipfile

import pytest

from .conftest import make_project

pytestmark = pytest.mark.integration


def _wait_execution(api, execution):
    # Eager mode finishes the run before the create call returns.
    return api.get(f"/api/executions/{execution['id']}").json()


def test_workflow_a_website(api, sample_app):
    project = make_project(api, "Website workflow")
    r = api.post(f"/api/projects/{project['id']}/discoveries", json={"url": sample_app + "/", "authorized": False})
    assert r.status_code == 422  # authorization confirmation is mandatory
    r = api.post(f"/api/projects/{project['id']}/discoveries", json={
        "url": sample_app + "/", "authorized": True, "login_url": "/login", "username": "demo@acme.test", "password": "Passw0rd!", "max_pages": 10})
    assert r.status_code == 202, r.text
    disc = api.get(f"/api/discoveries/{r.json()['id']}").json()
    assert disc["status"] == "completed", disc
    assert disc["login_result"]["success"] is True
    assert {p["title"].split(" |")[0] for p in disc["pages"]} >= {"Dashboard", "Customers", "New customer"}
    # The sign-in page redirects once signed in, so it is not crawled; the form is recorded at sign-in.
    assert disc["login_result"]["form"]["has_password"] is True
    assert any("logout" in s["url"] for s in disc["skipped"])  # destructive links are not crawled
    assert next(p for p in disc["pages"] if p["url"].endswith("/customers"))["requires_login"] is True

    job = api.post(f"/api/discoveries/{disc['id']}/generate", json={}).json()
    job = api.get(f"/api/generation-jobs/{job['id']}").json()
    assert job["status"] == "completed" and job["result"]["created"] >= 15 and job["result"]["invalid"] == 0
    assert job["result"]["ai"]["used"] is False  # no AI key in tests: deterministic planner only, and it says so
    cases = api.get(f"/api/projects/{project['id']}/test-cases").json()
    assert all(c["status"] == "generated" for c in cases)  # generated, not executed
    assert all(c["last_result"] is None for c in cases)

    pick = [c["id"] for c in cases if c["title"] in (
        "Verify login with valid credentials", "Verify login rejects invalid credentials", 'Verify navigation to "Customers"')
        or c["category"] == "boundary"]
    assert len(pick) >= 4
    ex = api.post(f"/api/projects/{project['id']}/executions", json={"test_case_ids": pick, "workers": 2}).json()
    ex = _wait_execution(api, ex)
    assert ex["status"] == "passed", [(r["test_title"], r["error_message"]) for r in ex["results"]]
    assert ex["passed"] == len(pick)
    assert {a["name"] for a in ex["reports"]} == {"report.html", "report.pdf"}
    detail = api.get(f"/api/results/{ex['results'][0]['id']}").json()
    assert detail["generated_code"].startswith("// Generated by LorvenLax")
    assert any(a["kind"] == "screenshot" for a in detail["artifacts"])
    shot = next(a for a in detail["artifacts"] if a["kind"] == "screenshot")
    resp = api.get(shot["url"])
    assert resp.status_code == 200 and resp.content[:4] == b"\x89PNG"
    assert "Passw0rd!" not in json.dumps(detail)

    html = api.get(f"/api/executions/{ex['id']}/report?format=html")
    assert html.status_code == 200 and "LorvenLax test report" in html.text
    pdf = api.get(f"/api/executions/{ex['id']}/report?format=pdf")
    assert pdf.status_code == 200 and pdf.content[:4] == b"%PDF"
    allure = zipfile.ZipFile(io.BytesIO(api.get(f"/api/executions/{ex['id']}/report?format=allure").content))
    results = [json.loads(allure.read(n)) for n in allure.namelist() if n.endswith("-result.json")]
    assert len(results) == len(pick) and all(r["status"] == "passed" for r in results)

    dash = api.get(f"/api/organizations/{api.org_id}/dashboard").json()
    assert dash["results"]["passed"] >= len(pick) and dash["executions"] >= 1


def test_failure_analysis_and_self_healing(api, sample_app):
    project = make_project(api, "Healing", sample_app)
    case = api.post(f"/api/projects/{project['id']}/test-cases", json={"title": "Sign in form uses old button text", "steps": [
        {"action": "navigate", "value": "/login"},
        {"action": "fill", "target": {"strategy": "label", "value": "Email"}, "value": "demo@acme.test"},
        {"action": "click", "target": {"strategy": "role", "value": "button", "name": "Sign in now"}},
        {"action": "assert_url", "value": "/dashboard"},
    ]}).json()
    ex = api.post(f"/api/projects/{project['id']}/executions", json={"test_case_ids": [case["id"]], "timeout_ms": 20000}).json()
    ex = _wait_execution(api, ex)
    assert ex["status"] == "failed"
    result = api.get(f"/api/results/{ex['results'][0]['id']}").json()
    assert result["failure"]["category"] == "locator_failure"
    assert result["failed_step_index"] == 2
    assert any(a["kind"] == "dom" for a in result["artifacts"])
    suggestion = result["healing_suggestions"][0]
    assert suggestion["suggested_target"] == {"strategy": "role", "value": "button", "name": "Sign in"}
    assert suggestion["status"] == "pending"
    # The test is unchanged until a person accepts the suggestion.
    steps = api.get(f"/api/projects/{project['id']}/test-cases/{case['id']}").json()["steps"]
    assert steps[2]["target"]["name"] == "Sign in now"
    r = api.post(f"/api/healing-suggestions/{suggestion['id']}", json={"decision": "accept"})
    assert r.status_code == 200
    after = api.get(f"/api/projects/{project['id']}/test-cases/{case['id']}").json()
    assert after["steps"][2]["target"]["name"] == "Sign in" and after["steps"][2]["action"] == "click"
    assert after["steps"][3] == {**steps[3], "id": after["steps"][3]["id"]}  # assertion untouched
    logs = api.get(f"/api/organizations/{api.org_id}/audit-logs").json()
    assert any(l["action"] == "healing.accepted" for l in logs)
    # Re-running now gets further, and fails for a different, honest reason (no password entered).
    ex2 = _wait_execution(api, api.post(f"/api/projects/{project['id']}/executions", json={"test_case_ids": [case["id"]], "timeout_ms": 20000}).json())
    r2 = ex2["results"][0]
    assert r2["status"] == "failed" and r2["failure"]["category"] != "locator_failure"


def test_workflow_b_api(api, sample_app):
    project = make_project(api, "API workflow")
    r = api.post(f"/api/projects/{project['id']}/api-collections", json={"spec_url": sample_app + "/openapi.json", "api_token": "demo-token"})
    assert r.status_code == 201, r.text
    coll = r.json()
    assert coll["base_url"] == sample_app and coll["endpoint_count"] == 5
    job = api.post(f"/api/api-collections/{coll['id']}/generate", json={}).json()
    job = api.get(f"/api/generation-jobs/{job['id']}").json()
    assert job["status"] == "completed" and job["result"]["created"] >= 20
